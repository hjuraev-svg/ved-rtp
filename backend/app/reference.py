def _expand(rows, pipeline, responsible, frequency):
    out = []
    for sid, code, name, group_key, sla, what, how in rows:
        out.append({
            "id": sid,
            "pipeline": pipeline,
            "code": f"{pipeline}_{code}",
            "name": name,
            "group_key": group_key,
            "description": what,
            "how_to_count": how,
            "data_source": "Данные вносит специалист в карточке сделки",
            "frequency": frequency,
            "responsible": responsible,
            "sla_days": sla,
        })
    return out


